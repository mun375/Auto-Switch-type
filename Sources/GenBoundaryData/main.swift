import Foundation
import SmartSwitchKit

// Regenerates the two data files BoundarySplitter ships with:
//   Resources/syllable-weights.txt  — syllable → frequency (from McBopomofo data.txt)
//   Resources/english-nosplit.txt   — English words a space must never split
//
// Usage (from the repo root): swift run gen-boundary-data
// Rerun after changing the lexicon, the syllable table or the split rules.

let repo = FileManager.default.currentDirectoryPath
let resources = "\(repo)/Sources/SmartSwitchKit/Resources"

func read(_ path: String) -> String {
    guard let text = try? String(contentsOfFile: path, encoding: .utf8) else {
        print("cannot read \(path) — run from the repo root")
        exit(1)
    }
    return text
}

// ── Syllable weights ──
var keyForSymbol: [Character: Character] = [:]
for (key, symbol) in DachenLayout.map where symbol.category != .tone {
    keyForSymbol[Character(symbol.bopomofo)] = key
}
let toneKeys: [Character: Character] = ["ˊ": "6", "ˇ": "3", "ˋ": "4", "˙": "7"]

var weights: [String: Double] = [:]
for line in read("\(repo)/vendor/McBopomofo/Source/Data/data.txt").split(separator: "\n") {
    let f = line.split(separator: " ")
    guard f.count == 3, !f[0].hasPrefix("_"), !f[0].contains("-"), f[1].count == 1,
        let score = Double(f[2])
    else { continue }
    var keys = ""
    var tone: Character = " "
    var ok = true
    for ch in f[0] {
        if let t = toneKeys[ch] { tone = t } else if let k = keyForSymbol[ch] { keys.append(k) } else { ok = false }
    }
    guard ok,
        let syllables = tone == " "
            ? ZhuyinParser.parse(keys: keys, appendFirstToneIfMissing: true)
            : ZhuyinParser.parse(keys: keys + String(tone)),
        syllables.count == 1
    else { continue }
    weights[syllables[0].bopomofo, default: 0] += pow(10, score)
}
let total = weights.values.reduce(0, +)
var weightLines = ["# syllable<TAB>share of typed characters. Generated by gen-boundary-data; do not edit."]
for (syllable, w) in weights.sorted(by: { $0.value > $1.value }) {
    weightLines.append("\(syllable)\t\(String(format: "%.6e", w / total))")
}
try! (weightLines.joined(separator: "\n") + "\n").write(
    toFile: "\(resources)/syllable-weights.txt", atomically: true, encoding: .utf8)
print("syllable-weights.txt: \(weights.count) syllables")

// ── No-split words ──
let splitter = BoundarySplitter(rankedLexicon: Lexicon.top3000Ranked, syllableWeight: [:])
var candidates = Set<String>()
for path in ["\(repo)/data/google-10000-english.txt", "/usr/share/dict/words"] {
    for w in read(path).split(separator: "\n") {
        let word = w.lowercased()
        if word.count >= 3, word.allSatisfy({ $0.isLetter && $0.isASCII }) { candidates.insert(word) }
    }
}
let noSplit = candidates.filter { splitter.splitAtSpace(keys: $0) != nil }.sorted()
try! (["# English words a space must not split. Generated by gen-boundary-data; do not edit."]
    + noSplit).joined(separator: "\n").appending("\n").write(
        toFile: "\(resources)/english-nosplit.txt", atomically: true, encoding: .utf8)
print("english-nosplit.txt: \(noSplit.count) words")
